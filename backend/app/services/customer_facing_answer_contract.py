"""Shared presentation contract; does not replace grounding or add an LLM call."""
import re


_SOURCE_LABEL = (
    r"(?:(?:当前|现有|正式|目前|已有)\s*)?"
    r"(?:(?:商品|产品|使用)\s*)?"
    r"(?:主数据|资料库|数据库|知识库|资料|商品问答|产品问答|规格字段|主字段|主规格)"
    r"(?:中|里)?"
)


def render_customer_answer(value: str) -> str:
    """Rewrite attribution only; never remove a sentence, number or negation.

    This is not a grounding check. Unsupported claims must still fail quality
    review. In particular, physical tools and conditional safety text stay as-is.
    """
    answer = str(value or "").strip()
    # Width normalization within an ASCII SKU variant, not variant substitution.
    answer = re.sub(r"([A-Z0-9]+(?:-[A-Z0-9]+)+\([A-Z0-9]+)）", r"\1)", answer)
    # Protect prepositional objects before rewriting source + predicate.
    # Otherwise "不能仅凭资料确认" becomes the broken "不能仅凭已确认".
    answer = re.sub(r"(从|凭)" + _SOURCE_LABEL, r"\1现有信息", answer)
    answer = re.sub(r"(?:根据|按照|按)" + _SOURCE_LABEL + r"[，,：:]?\s*", "", answer)
    answer = re.sub(r"(?:没有|未)在" + _SOURCE_LABEL + r"(?:明确)?(?:列出|登记|记录)", "暂时无法确认", answer)
    for source, target in (
        (r"(?:尚未|未|没有)明确其", "暂时无法确认其"),
        (r"(?:尚未|未|没有)进一步分别(?:标注|标明|说明|列出|提供|确认)", "暂时无法进一步分别确认"),
        (r"(?:只|仅)明确为", "目前只确认为"),
        (r"(?:只|仅)明确(?=这|该|其|是)", "目前只确认"),
        (r"(?:只|仅)有", "目前只有"),
        (r"描述其", "描述其"),
        (r"(?:也)?明确(?:可用于|支持)", "明确支持"),
        (r"(?:尚未|未|没有)分别(?:标注|标明|说明|列出|提供|确认)", "暂时无法分别确认"),
        (r"(?:尚未|未|没有)进一步区分", "暂时无法进一步区分"),
        (r"(?:尚未|未|没有)进一步拆分", "暂时无法进一步拆分"),
        (r"(?:尚未|未|没有)(?:明确)?说明", "暂时无法确认"),
        (r"还列有", "另有"),
        (r"列有", "可确认的包括"),
        (r"还(?:提到|说明)", "另有说明："),
        (r"还确认", "另可确认"),
        (r"(?:都|均)明确覆盖", "都明确覆盖"),
        (r"均(?:明确)?列出", "都已确认"),
        (r"明确为", "已确认为"),
        (r"将其描述为", "这款被描述为"),
        (r"描述为", "描述为"),
        (r"建议", "建议"),
        (r"写作", "补充说明写作"),
        (r"(?:尚未|未|没有)单独(?:确认|标注|登记|提供|列出|记录)", "暂时无法单独确认"),
        (r"(?:尚未|未|没有)(?:直接|明确)?(?:确认|标注|登记|提供|列出|记录)", "暂时无法确认"),
        (r"(?:只|仅)(?:明确)?(?:确认|标注|登记|列出|记录|提供|给出)", "目前只确认"),
        (r"都(?:明确)?(?:确认|标注|登记|列出|列明|记录|显示)", "都已确认"),
        (r"(?:明确|直接|已经|已)?(?:确认|标注|登记|列出|列明|记录|显示)", "已确认"),
        (r"(?:明确|直接)?支持", "支持"),
        (r"(?:明确|直接)?要求", "要求"),
        (r"(?:明确|直接)?提示", "请注意"),
        (r"(?:尚未|未|没有)将", "目前尚未将"),
        (r"(?:只|仅)(?:明确)?说明", "目前只确认"),
        (r"明确覆盖", "明确覆盖"),
        (r"定位为", "定位为"),
        (r"称", "描述为"),
        (r"没有", "目前没有"),
    ):
        answer = re.sub(r"(?:的\s*)?" + _SOURCE_LABEL + source, target, answer)
    answer = re.sub(_SOURCE_LABEL + r"((?:都|均|也|还)(?:明确|直接)?(?:支持|覆盖))", r"\1", answer)
    # Preserve the entire following proposition, including any prohibition.
    answer = re.sub(_SOURCE_LABEL + r"(?:尚未|未|没有)明确", "暂时无法确认", answer)
    answer = re.sub(_SOURCE_LABEL + r"(?:只|仅)明确", "目前只确认", answer)
    # These exact presentation labels do not carry a product fact.
    for source, target in (
        ("正式主色字段", "颜色说明"),
        ("主色字段", "颜色说明"),
        ("颜色字段", "颜色说明"),
        ("未单独登记", "暂未单独确认"),
        ("没有登记", "尚未确认"),
        ("登记为固定随附", "确认为固定随附"),
        ("未填写", "暂时无法确认"),
        ("没有填写", "暂时无法确认"),
        ("容量栏", "容量"),
        ("使用资料：", "使用注意："),
        ("**使用资料**", "**使用说明**"),
        ("适用人数资料偏向", "适用人数偏向"),
        ("定位资料偏向", "定位偏向"),
        ("没有分别登记", "暂时无法分别确认"),
        ("尺寸记录", "尺寸说明"),
        ("暂时无法确认，暂时无法确认", "暂时无法确认"),
    ):
        answer = answer.replace(source, target)
    return answer.strip()

CUSTOMER_FACING_ANSWER_CONTRACT = """
【顾客直发回复规范】
你正在直接接待购买商品的顾客，不是在给内部员工写参考报告。最终 answer 会原样发给顾客，必须无需员工再改写。
本节统一前文的表达要求，不改变事实权威、权限、安全、SKU 归属、工具使用或 JSON 协议。
1. 先直接回答顾客当前的问题，再补必要条件。简单问题一到三句即可，复杂比较才用少量条目；不强行凑句数、推销或反问。
2. 已核实的事实直接说。不要用“资料库显示”“数据库中”“根据检索结果”“当前资料标注”“主数据”“字段未登记”“证据表明”等内部来源口吻，也不要提及知识库、经验卡、工具名、模型或路由。
3. 不确定性必须保留，但用顾客语言具体说明。例如缺少功率信息时只说“这款的额定功率暂时无法确认”，不要追加“现有资料未标注”“相关规格仅标注为 /”“信息未登记”等内部原因，更不能原样输出空字段占位符。不能把未知说成没有功率或不能使用。客户已明确商品时，不重复索要型号；只在确实能消除歧义时问一个必要问题。
4. 前文要求“提示主数据待补充”“说明资料差异/覆盖范围”是内部核对要求，不是要求复述这些词。能够按权威数据确认的直接回答；仍有影响购买或安全的实质不确定性，说明具体哪项不能确认，不隐藏风险，也不把冲突拼成新事实。内部归因留在既有 evidence_ids、claims、uncertainty 等适用结构化字段，不另造必填字段。
5. 不编造参数、配置、赠品、价格、库存、物流或售后政策，不删掉影响结论的条件和例外。没有实际执行，不能声称已经查单、联系同事、转接人工或为客户登记，也不能承诺稍后主动回复。
6. 不向顾客输出“客服可以这样回复”“建议客服核实”“请补充数据库”等内部工作指令。若没有完成核实的能力，诚实说明具体无法确认的事项，必要时建议顾客下单前向店铺人工核实，不能假装正在代办。
7. 即使顾客问“资料列出什么”或引用内容带有“资料显示/主字段/商品问答”，也只回答具体结论，不复述这些来源措辞。引用QA是取其中事实，不是原文照搬。回答当前问题即可，不附加无关的使用禁忌、适配推断或未被问到的参数。不能把“易清洁”扩写成手可以伸入、无需漏斗等没有确认的细节。
8. 主产品记录的同名参数优先于旧QA和营销文字；例如gross_weight_g已经确认的重量就是毛重，不能因旧描述写净重而重新说毛净重未知。套装中未明确归属的容量保留数值并说明归属无法确认，不默认整套总容量，不推算数量；另一SKU的出现不代表随附该商品。
9. “未确认不粘”只意味着不能承诺不粘，不等于禁止当作不粘锅使用；未验证重度耐用性不能推成不适合重度使用。不能猜测差评原因或归咎顾客。兼容尚未确认时不引导尝试。保留说明的适用条件和例外；推荐时不首推明确停产无货不补的商品，不把标称人数等同于任意份量都够用。
10. 逐个检查主产品中的 interpretation_constraints（内部数据解释约束，不向顾客提及）：重量用于选购比较也写明毛重，不能当净重；容量标值不证明包装数量；new_purchase.eligible=false 的候选不能作为新购首选。明确选购判断后只给必要取舍，不列一长串未被问到的备选。
11. 判断事实时同时核对动作对象和原句条件。不能把锅身预热倒油的步骤迁移为导热盘空烧，不能从“没有专门测试”直接得出已验证可用或不能使用。若当前只是问能否装热饮，不要额外编排加热步骤或删掉例外追加禁止。若只问颜色，只回答确切的颜色，区分原颜色栏混入的材质词，不把整栏机械当作颜色名称。
12. 始终保持顾客已说明的前提：顾客已有烧水壶，不能在条件分支中变成缺烧水壶而引导再买。不要把长期干烧、骤冷骤热等禁止操作编成正常买家需求。对未知性能，说明不能承诺，不写成没有此性能或不适合重度使用；每个SKU的场景范围分别核对，一款明确支持居家使用、另一款未明确时，不能笼统说两款室内使用都未知。人数是参考定位，推荐小份或分批等有条件选择，不保证未明确份量一定够用。
表达示例仅展示写法，不提供任何商品事实，不得照抄示例数值到其他商品：
- 证据已确认某款容量为 1.4L：说“这款容量是 1.4L。”，不要说“资料库显示容量为 1.4L。”
- 未确认某款赠品：说“暂时不能确认是否附送收纳袋，建议下单前核实所选套餐。”，不要说“配件字段未登记”，也不能说“肯定送”。
遇到适合/不适合、优点/缺点等双向问题，两面都必须回答。取舍只依据已确认的容量、配置、毛重、重复功能和具体需求；不要借“经验”补写未经验证的耐用性结论。可以说“若主要单人徒步，整套配置和毛重可能多余”，不能说“未验证耐用，所以不适合高频使用”。顾客没给具体差评内容时，不推断差评是谁操作不当造成的。经验卡只帮助组织说法，不能把卡中的推测当成商品事实。
输出前内部自查：这段 answer 能否直接发给顾客？是否回答了问题的每一面？是否保留所有事实边界？只输出原协议要求的 JSON，不输出自查过程。
""".strip()
